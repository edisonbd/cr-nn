def clean(raw: bytes) -> str:
    txt = raw.decode("utf-8", errors="ignore")
    txt = re.sub(r"\r\n?", "\n", txt)
    # drop the boilerplate header/footer
    txt = re.sub(r"\*\*\* ?START OF (THE|THIS) PROJECT GUTENBERG.*?\*\*\*",
                 "", txt, flags=re.IGNORECASE)
    txt = re.sub(r"\*\*\* ?END OF (THE|THIS) PROJECT GUTENBERG.*",
                 "", txt, flags=re.IGNORECASE)
    txt = re.sub(r"\n{3,}", "\n\n", txt)
    return txt.strip()


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else "data/books2"
    os.makedirs(outdir, exist_ok=True)
    total, ok = 0, 0
    for i, bid in enumerate(IDS):
        url = f"https://www.gutenberg.org/cache/epub/{bid}/pg{bid}.txt"
        dst = f"{outdir}/{bid}.txt"
        if os.path.exists(dst) and os.path.getsize(dst) > 1000:
            continue
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "cr-nn/1.0"})
            with urllib.request.urlopen(req, timeout=30) as r:
                body = r.read()
            txt = clean(body)
            if len(txt) > 2000:
                with open(dst, "w", encoding="utf-8") as f:
                    f.write(txt)
                total += len(txt)
                ok += 1
        except Exception:
            pass
        if (i + 1) % 100 == 0:
            print(f"  {i+1}/{len(IDS)} ok={ok} bytes={total}", flush=True)
    print(f"done ok={ok} bytes={total} ({total/1e6:.1f}MB)")


if __name__ == "__main__":
    main()
